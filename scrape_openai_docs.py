#!/usr/bin/env python3
"""
Scrape OpenAI API docs as individual markdown files from developers.openai.com.

The site publishes two machine-readable manifests of the API reference:

  /api/reference/index.md   the full navigation tree (resources, subresources,
                            methods). Every entry is served at `<path>/index.md`.
  /api/reference/llms.txt   a flat manifest with titles and descriptions. Every
                            entry is served at `<path>.md`.

Neither is a superset. index.md carries the current resource tree but omits the
streaming/websocket event pages and the section overviews; llms.txt carries
those but still lists the pre-restructure `resources/organization/*` paths,
which now serve short "generated by Stainless" placeholder stubs. This script
takes the union of both and drops the stubs at fetch time.

Discovery is plain HTTP, so it runs anywhere -- no browser required.
"""

import argparse
import json
import os.path
import re
import sys
import time
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from functools import lru_cache
from pathlib import Path
from urllib.parse import urljoin

import requests

BASE_URL = "https://developers.openai.com"
REF_PREFIX = "/api/reference/"
REF_URL = BASE_URL + REF_PREFIX
LEGACY_PREFIX = "/docs/api-reference/"

DOCS_DIR = Path("docs")
CACHE_FILE = DOCS_DIR / ".url_cache.json"
CACHE_VERSION = 3

# Paths under docs/ that this script does not manage and must never prune.
PRESERVED = {"plans"}

REQUEST_TIMEOUT = 60
DELAY_BETWEEN_REQUESTS = 0.15
MAX_RETRIES = 3
RETRYABLE_STATUS = {403, 429, 500, 502, 503, 504}
DEFAULT_JOBS = 4

# A retired page that now serves a placeholder instead of real content. These
# are short and always carry this trailer.
STUB_MARKER = "This API reference page is generated by Stainless."
STUB_MAX_BYTES = 2000

MD_LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)\s]+)\)")
# A fenced json block, with the newline before it, through its closing fence
# (or end of file if unclosed).
JSON_FENCE_RE = re.compile(r"\n^```json.*?(?:^```[^\n]*|\Z)", re.M | re.S)


# --------------------------------------------------------------------------
# Discovery
# --------------------------------------------------------------------------


def discover_pages() -> list[dict]:
    """Build the page list from index.md and llms.txt.

    Each page is {"path", "scheme"} where `path` is the slug relative to
    /api/reference/ and `scheme` selects the URL form that serves it:
    "index" -> <path>/index.md, "flat" -> <path>.md
    """
    print("Discovering pages...")
    sources = [
        (f"{REF_URL}index.md", REF_PREFIX, "/index.md", "index"),
        (f"{REF_URL}llms.txt", REF_URL, ".md", "flat"),
    ]
    pages: dict[str, dict] = {}
    for url, prefix, suffix, scheme in sources:
        print(f"  GET {url}")
        resp = requests.get(url, timeout=REQUEST_TIMEOUT)
        resp.raise_for_status()
        before = len(pages)
        for _, href in MD_LINK_RE.findall(resp.text):
            if not href.startswith(prefix) or not href.endswith(suffix):
                continue
            path = href[len(prefix) : -len(suffix)]
            if path == "llms" or path.endswith("llms-full"):
                continue
            pages.setdefault(path, {"path": path, "scheme": scheme})
        print(f"    {len(pages) - before} new pages")

    print(f"  {len(pages)} pages total")
    return sorted(pages.values(), key=lambda p: p["path"])


def source_url(page: dict) -> str:
    suffix = "/index.md" if page["scheme"] == "index" else ".md"
    return f"{REF_URL}{page['path']}{suffix}"


# --------------------------------------------------------------------------
# Path mapping
# --------------------------------------------------------------------------


def local_path(page: dict) -> Path:
    """Map a page slug to its file under docs/.

    resources/audio                                  -> docs/audio/index.md
    resources/audio/subresources/speech/methods/create
                                                     -> docs/audio/speech/create.md
    resources/responses/streaming-events             -> docs/responses/streaming-events.md
    resources/$shared                                -> docs/shared/index.md
    resources/fine_tuning/subresources/methods       -> docs/fine_tuning/methods/index.md
    overview                                         -> docs/overview.md
    workload-identity-federation                     -> docs/workload-identity-federation.md
    """
    raw = page["path"].split("/")
    if raw[0] == "resources":
        raw = raw[1:]

    def clean(segments: list[str]) -> list[str]:
        return [s.lstrip("$") for s in segments if s != "subresources"]

    # "methods" is only a marker when it introduces the trailing method name.
    # fine_tuning has a *subresource* named "methods", so a bare `in` test on
    # the segments would misfile it as fine_tuning's index page.
    if len(raw) >= 2 and raw[-2] == "methods":
        return DOCS_DIR.joinpath(*clean(raw[:-2]), f"{raw[-1]}.md")

    parts = clean(raw)
    if page["scheme"] == "index":
        return DOCS_DIR.joinpath(*parts, "index.md")
    return DOCS_DIR.joinpath(*parts[:-1], f"{parts[-1]}.md")


# --------------------------------------------------------------------------
# Content cleanup
# --------------------------------------------------------------------------


def strip_internal_ast(content: str) -> str:
    """Drop fenced json blocks holding the doc generator's internal AST.

    The streaming/websocket event pages inline the generator's declaration graph
    ("kind": "HttpDeclProperty", "oasRef", ...) once per event, which balloons a
    single page past 20 MB. The surrounding headings, descriptions, schema names
    and example payloads are kept; only the AST dumps go.
    """

    def drop(match: re.Match) -> str:
        block = match.group(0)
        return "" if '"kind": "HttpDecl' in block or '"oasRef"' in block else block

    # The leading "\n" lets a block on the first line match like any other.
    stripped = JSON_FENCE_RE.sub(drop, "\n" + content)[1:]
    return re.sub(r"\n{3,}", "\n\n", stripped)


@lru_cache(maxsize=None)
def resolve_legacy(slug: str) -> str | None:
    """Resolve a legacy /docs/api-reference/<slug> link to a canonical page slug.

    The docs cross-reference each other almost entirely through the old
    platform.openai.com-era paths (`/docs/api-reference/runs/submitToolOutputs`),
    which bear no mechanical relation to the current tree. Rather than guess at
    an alias table, ask the site: it still serves redirects for these, and that
    redirect map is authoritative. Results are memoised, and in practice a whole
    run needs only a few dozen lookups.

    Unrecognised slugs redirect to the reference overview; that is the site's
    catch-all, not a real answer, so it counts as unresolved and the link is
    left pointing at openai.com.
    """
    try:
        resp = requests.head(
            f"{BASE_URL}{LEGACY_PREFIX}{slug}", allow_redirects=True, timeout=REQUEST_TIMEOUT
        )
    except requests.RequestException:
        return None

    if not resp.url.startswith(REF_URL):
        return None
    canonical = resp.url[len(REF_URL) :].split("#", 1)[0].rstrip("/")
    if canonical == "overview" and slug != "overview":
        return None
    return canonical


def page_slug(url: str) -> str | None:
    """Reduce a site-absolute link to a page slug, or None if it isn't one."""
    if url.startswith(REF_PREFIX):
        slug = url[len(REF_PREFIX) :].split("#", 1)[0].split("?", 1)[0]
        for suffix in ("/index.md", ".md", "/"):
            if slug.endswith(suffix):
                return slug[: -len(suffix)]
        return slug
    if url.startswith(LEGACY_PREFIX):
        slug = url[len(LEGACY_PREFIX) :].split("#", 1)[0].split("?", 1)[0].rstrip("/")
        return resolve_legacy(slug) if slug else None
    return None


def fix_links(content: str, link_map: dict[str, Path], page: dict) -> str:
    """Point links at local files where we have them, absolutise the rest.

    Nothing relative is left behind: a link we cannot resolve to a local file
    becomes an absolute developers.openai.com URL, so the mirror never contains
    a dangling local path. A handful of links are broken upstream too (e.g. the
    fine-tuning permission pages link to `../admin-api-keys`, which 404s on the
    site); those stay broken, but visibly so, and point at OpenAI rather than at
    a missing file here.
    """
    here = link_map[page["path"]].parent
    page_url = f"{REF_URL}{page['path']}/"

    def replace(match: re.Match) -> str:
        text, url = match.groups()
        # Some pages link to each other by full URL; treat those as site paths.
        if url.startswith(f"{BASE_URL}/"):
            url = url.removeprefix(BASE_URL)
        if url.startswith(("http://", "https://", "#", "mailto:")):
            return match.group(0)

        absolute = url if url.startswith("/") else urljoin(page_url, url).removeprefix(BASE_URL)
        target = link_map.get(page_slug(absolute))
        if target is not None:
            return f"[{text}]({os.path.relpath(target, here)})"
        return f"[{text}]({BASE_URL}{absolute})"

    return MD_LINK_RE.sub(replace, content)


# --------------------------------------------------------------------------
# Fetching
# --------------------------------------------------------------------------


def fetch_markdown(url: str) -> tuple[str | None, int]:
    """Return (content, status); content is None on failure, status 0 if no response."""
    status = 0
    for attempt in range(MAX_RETRIES):
        if attempt:
            time.sleep(2 ** (attempt - 1))
        try:
            resp = requests.get(url, timeout=REQUEST_TIMEOUT)
        except requests.RequestException:
            status = 0
            continue
        if resp.status_code == 200:
            return resp.text, 200
        status = resp.status_code
        if status not in RETRYABLE_STATUS:
            break
    return None, status


def is_stub(content: str) -> bool:
    return len(content) < STUB_MAX_BYTES and STUB_MARKER in content


# --------------------------------------------------------------------------
# Pruning
# --------------------------------------------------------------------------


def prune(expected: set[Path]) -> list[Path]:
    """Delete managed files under docs/ that are no longer part of the site."""

    def managed(path: Path) -> bool:
        return path.relative_to(DOCS_DIR).parts[0] not in PRESERVED

    removed = [p for p in sorted(DOCS_DIR.rglob("*.md")) if managed(p) and p not in expected]
    for path in removed:
        path.unlink()

    for directory in sorted(DOCS_DIR.rglob("*"), reverse=True):
        if directory.is_dir() and managed(directory) and not any(directory.iterdir()):
            directory.rmdir()

    return removed


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--no-discover",
        action="store_true",
        help="reuse the cached page list instead of refetching the manifests",
    )
    parser.add_argument(
        "--skip-existing",
        action="store_true",
        help="leave files that are already on disk alone (development shortcut)",
    )
    parser.add_argument(
        "--no-prune",
        action="store_true",
        help="keep local files that are no longer published by the site",
    )
    parser.add_argument(
        "--keep-internal-ast",
        action="store_true",
        help="do not strip the generator's internal AST json blocks",
    )
    parser.add_argument(
        "--jobs", type=int, default=DEFAULT_JOBS, help=f"parallel fetches (default {DEFAULT_JOBS})"
    )
    parser.add_argument(
        "--max-failures",
        type=int,
        default=10,
        help="exit non-zero if more than this many pages fail (default 10)",
    )
    return parser.parse_args(argv)


def load_cache() -> list[dict]:
    if not CACHE_FILE.exists():
        sys.exit("ERROR: no page cache found; run without --no-discover first.")
    data = json.loads(CACHE_FILE.read_text())
    if not isinstance(data, dict) or data.get("version") != CACHE_VERSION:
        sys.exit(f"ERROR: page cache is not version {CACHE_VERSION}; rerun discovery.")
    print(f"Loaded {len(data['pages'])} pages from cache")
    return data["pages"]


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    print(f"OpenAI API docs scraper -> {DOCS_DIR}/")

    if args.no_discover:
        pages = load_cache()
    else:
        pages = discover_pages()
        CACHE_FILE.write_text(json.dumps({"version": CACHE_VERSION, "pages": pages}, indent=2) + "\n")
        print(f"  cache written to {CACHE_FILE}")

    link_map = {page["path"]: local_path(page) for page in pages}
    # A collision means two slugs claim one file and one would clobber the other.
    collisions = [t for t, n in Counter(link_map.values()).items() if n > 1]
    for target in collisions:
        slugs = [slug for slug, t in link_map.items() if t == target]
        print(f"ERROR: {', '.join(slugs)} all map to {target}")
    if collisions:
        return 2

    def handle(page: dict, i: int) -> tuple[str, int]:
        url = source_url(page)
        target = link_map[page["path"]]
        progress = f"[{i}/{len(pages)}]"

        if args.skip_existing and target.exists():
            print(f"{progress} SKIP  {target}")
            return "skipped", 0

        content, status = fetch_markdown(url)
        if content is None:
            print(f"{progress} FAIL  HTTP {status}  {url}")
            return "failed", status
        if is_stub(content):
            print(f"{progress} STUB  {page['path']} (retired, not written)")
            return "stub", status

        if not args.keep_internal_ast:
            content = strip_internal_ast(content)
        content = fix_links(content, link_map, page)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(f"{progress} OK    {target} {len(content):,} chars")

        time.sleep(DELAY_BETWEEN_REQUESTS)
        return "written", status

    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        outcomes = list(pool.map(handle, pages, range(1, len(pages) + 1)))

    counts = Counter(outcome for outcome, _ in outcomes)
    failures = [
        (page["path"], status)
        for page, (outcome, status) in zip(pages, outcomes)
        if outcome == "failed"
    ]

    pruned = []
    if not args.no_prune:
        # Failed fetches keep their existing file: a transient error is not
        # evidence the page was retired. Genuinely removed pages fall out of
        # the manifests and so are absent from `pages` entirely.
        pruned = prune(
            {link_map[page["path"]] for page, (o, _) in zip(pages, outcomes) if o != "stub"}
        )

    print("\nSUMMARY")
    for label, n in [
        ("written", counts["written"]),
        ("skipped", counts["skipped"]),
        ("retired stub", counts["stub"]),
        ("pruned", len(pruned)),
        ("failed", len(failures)),
    ]:
        print(f"  {label + ':':<14}{n}")
    for path, status in failures:
        print(f"    HTTP {status}  {path}")

    if len(failures) > args.max_failures:
        print(f"\nFAILED: {len(failures)} pages failed (limit {args.max_failures}).")
        return 1

    print(f"\nDone. {counts['written']} files written to {DOCS_DIR}/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
